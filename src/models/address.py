class Address:
    def __init__(self, state, city, neighborhood, street, number, postal_code, complement, label, company):
        self.state = state
        self.city = city
        self.neighborhood = neighborhood
        self.street = street
        self.number = number
        self.postal_code = postal_code
        self.complement = complement
        self.label = label
        self.company = company
